// Builds the installable, offline web version into dist/.
//   npm run build:web
// 1. `expo export --platform web` builds the single-page app (files in public/ are copied as they are).
// 2. A service worker (sw.js) is written that saves every file of this build on the first visit,
//    so the app keeps working with no connection afterwards.
// 3. index.html gets the manifest, the home-screen icon tags and the service worker registration.
import { execSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const dist = join(root, 'dist');

execSync('npx expo export --platform web --output-dir dist --clear', { cwd: root, stdio: 'inherit' });

const files = [];
(function walk(dir) {
  for (const name of readdirSync(dir)) {
    const path = join(dir, name);
    if (statSync(path).isDirectory()) walk(path);
    else files.push('/' + relative(dist, path).split('\\').join('/'));
  }
})(dist);
const precache = files.filter(f => f !== '/sw.js' && !f.endsWith('.map')).sort();
const version = createHash('sha256').update(precache.join('\n')).digest('hex').slice(0, 12);

writeFileSync(join(dist, 'sw.js'), `// Generated by scripts/build-web.mjs. Saves this build for offline use.
const CACHE = 'akada-${version}';
const FILES = ${JSON.stringify(['/', ...precache])};

self.addEventListener('install', event => {
  event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(FILES)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', event => {
  event.waitUntil(caches.keys()
    .then(keys => Promise.all(keys.filter(key => key.startsWith('akada-') && key !== CACHE).map(key => caches.delete(key))))
    .then(() => self.clients.claim()));
});

self.addEventListener('fetch', event => {
  const request = event.request;
  if (request.method !== 'GET' || new URL(request.url).origin !== self.location.origin) return;
  // Pages: try the network for the newest version, fall back to the saved app when offline.
  if (request.mode === 'navigate') {
    event.respondWith(fetch(request).catch(() => caches.match('/index.html')));
    return;
  }
  // Everything else: saved copy first, then the network (and save what comes back).
  event.respondWith(caches.match(request).then(hit => hit || fetch(request).then(response => {
    if (response.ok) { const copy = response.clone(); caches.open(CACHE).then(cache => cache.put(request, copy)); }
    return response;
  })));
});
`);

const head = `
    <link rel="manifest" href="/manifest.webmanifest" />
    <meta name="theme-color" content="#1570E6" />
    <meta name="description" content="Free offline practice questions for Nigerian SS1–SS3 students." />
    <link rel="apple-touch-icon" href="/icons/apple-touch-icon.png" />
    <meta name="apple-mobile-web-app-capable" content="yes" />
    <meta name="mobile-web-app-capable" content="yes" />
    <meta name="apple-mobile-web-app-title" content="Akada" />
    <meta name="apple-mobile-web-app-status-bar-style" content="default" />
    <script>if ('serviceWorker' in navigator) window.addEventListener('load', () => navigator.serviceWorker.register('/sw.js'));</script>
  `;
const indexPath = join(dist, 'index.html');
let html = readFileSync(indexPath, 'utf8');
html = html.replace('</head>', `${head}</head>`).replace(/<title>[^<]*<\/title>/, '<title>Akada: SS1–SS3 practice</title>');
writeFileSync(indexPath, html);

const mb = precache.reduce((sum, f) => sum + statSync(join(dist, f)).size, 0) / 1048576;
console.log(`Web build ready in dist/: ${precache.length} files (${mb.toFixed(1)} MB) saved for offline use, cache ${version}`);
